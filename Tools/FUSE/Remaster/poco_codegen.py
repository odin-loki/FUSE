#!/usr/bin/env python3
"""Generate the Python POCO mirror from the JSON Schemas (docs/plans/FUSE_REMASTER_PLAN.md §2.3, W0.1).

``Content/schemas/poco/*.schema.json`` is the single source: the C++ structs in
``Source/FUSE/Remaster/include/fuse/remaster/poco.hpp`` are checked against it by ``remaster_poco_schema_parity``,
and this script writes ``fuse_ai/poco_types.py`` (dataclasses + ``from_dict`` / ``to_dict``) from it, so C++ and
Python cannot drift apart. ``--check`` fails when the committed module is stale (ctest ``remaster_poco_python``),
and then round-trips sample records through the generated module.

    python poco_codegen.py [--schemas <dir>] [--out <file>] [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
DEFAULT_SCHEMAS = REPO / "Content" / "schemas" / "poco"
DEFAULT_OUT = HERE / "fuse_ai" / "poco_types.py"


def class_name(schema_name: str) -> str:
    return "".join(p.capitalize() for p in schema_name.split("_")) if schema_name != "poco" else "Record"


def spec_of(prop: dict) -> Tuple:
    """A compact type spec: ("str"|"bool"|"int"|"float"|"any"), ("enum", values), ("ref", name),
    ("list", spec), ("opt", spec)."""
    if "$ref" in prop:
        return ("ref", prop["$ref"].split(".schema.json")[0])
    if "oneOf" in prop:
        alts = prop["oneOf"]
        return ("opt", spec_of(alts[0]))
    if "const" in prop:
        return ("str",)
    if "enum" in prop:
        return ("enum", tuple(prop["enum"]))
    t = prop.get("type")
    if t == "array":
        return ("list", spec_of(prop.get("items", {})))
    return {"string": ("str",), "boolean": ("bool",), "integer": ("int",), "number": ("float",)}.get(t, ("any",))


def py_type(spec: Tuple) -> str:
    k = spec[0]
    if k == "ref":
        return class_name(spec[1])
    if k == "opt":
        return f"Optional[{py_type(spec[1])}]"
    if k == "list":
        return f"List[{py_type(spec[1])}]"
    if k == "enum":
        return "str"
    return {"str": "str", "bool": "bool", "int": "int", "float": "float"}.get(k, "Any")


def default_of(spec: Tuple, prop: dict) -> str:
    k = spec[0]
    if k == "opt":
        return "None"
    if k == "list":
        n = prop.get("minItems")
        if n is not None and n == prop.get("maxItems"):
            return f"field(default_factory=lambda: [{'0.0' if spec[1][0] == 'float' else '0'}] * {n})"
        return "field(default_factory=list)"
    if k == "ref":
        return f"field(default_factory={class_name(spec[1])})"
    if k == "enum":
        return repr(spec[1][0])
    if "const" in prop:
        return repr(prop["const"])
    return {"str": "''", "bool": "False", "int": "0", "float": "0.0"}.get(k, "None")


def load_schemas(d: Path) -> Dict[str, dict]:
    return {p.name[: -len(".schema.json")]: json.loads(p.read_text(encoding="utf-8")) for p in sorted(d.glob("*.schema.json"))}


def generate(schemas: Dict[str, dict]) -> str:
    # Dependencies first (refs before users) so default_factory names resolve.
    order: List[str] = []

    def visit(n: str, stack: Tuple[str, ...] = ()) -> None:
        if n in order or n in stack:
            return
        for prop in schemas[n].get("properties", {}).values():
            s = spec_of(prop)
            while s[0] in ("opt", "list"):
                s = s[1]
            if s[0] == "ref" and s[1] in schemas:
                visit(s[1], stack + (n,))
        order.append(n)

    for n in schemas:
        visit(n)
    out = [
        '"""GENERATED by Tools/FUSE/Remaster/poco_codegen.py from Content/schemas/poco/*.schema.json. Do not edit.',
        "",
        "Python mirror of fuse_poco (Source/FUSE/Remaster/include/fuse/remaster/poco.hpp): one dataclass per schema,",
        "``from_dict`` / ``to_dict`` with the same leniency as the C++ reader (missing fields keep defaults, unknown",
        'members are kept in ``extra``, payloads of kinds outside the plan set stay raw dicts)."""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field, fields as dc_fields",
        "from typing import Any, Dict, List, Optional",
        "",
        "SCHEMA = 'fuse.poco/1'",
        "",
    ]
    specs: Dict[str, Dict[str, Tuple]] = {}
    for n in order:
        props = schemas[n].get("properties", {})
        specs[n] = {k: spec_of(v) for k, v in props.items()}
        out.append("")
        out.append("@dataclass")
        out.append(f"class {class_name(n)}:")
        desc = schemas[n].get("description", "")
        out.append(f'    """{desc}"""')
        for k, v in props.items():
            if n == "poco" and k == "payload":
                out.append("    payload: Any = field(default_factory=dict)")
                continue
            s = specs[n][k]
            out.append(f"    {k}: {py_type(s)} = {default_of(s, v)}")
        out.append("    extra: Dict[str, Any] = field(default_factory=dict)")
        out.append("")
    out.append("")
    out.append("SPECS: Dict[str, Dict[str, tuple]] = " + repr(specs))
    out.append("CLASSES = {" + ", ".join(f"{n!r}: {class_name(n)}" for n in order) + "}")
    out.append("KINDS = " + repr(sorted(k for k in schemas if any(
        b.get("if", {}).get("properties", {}).get("kind", {}).get("const") == k for b in schemas.get("poco", {}).get("allOf", [])))))
    out.append(RUNTIME)
    return "\n".join(out) + "\n"


RUNTIME = '''

class PocoError(ValueError):
    pass


def _read(spec: tuple, v: Any, path: str) -> Any:
    k = spec[0]
    if k == "opt":
        return None if v is None else _read(spec[1], v, path)
    if k == "str":
        if v is None:
            return ""
        if not isinstance(v, str):
            raise PocoError(f"{path}: expected a string")
        return v
    if k == "bool":
        if not isinstance(v, bool):
            raise PocoError(f"{path}: expected a boolean")
        return v
    if k == "int":
        if isinstance(v, bool) or not isinstance(v, (int, float)) or v != int(v):
            raise PocoError(f"{path}: expected an integer")
        return int(v)
    if k == "float":
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            raise PocoError(f"{path}: expected a number")
        return float(v)
    if k == "enum":
        if v not in spec[1]:
            raise PocoError(f"{path}: unknown enum value {v!r}")
        return v
    if k == "list":
        if not isinstance(v, list):
            raise PocoError(f"{path}: expected an array")
        return [_read(spec[1], e, f"{path}[{i}]") for i, e in enumerate(v)]
    if k == "ref":
        return from_dict(spec[1], v, path)
    return v


def _write(spec: tuple, v: Any) -> Any:
    k = spec[0]
    if k == "opt":
        return None if v is None else _write(spec[1], v)
    if k == "list":
        return [_write(spec[1], e) for e in v]
    if k == "ref":
        return to_dict(v)
    return v


def from_dict(schema: str, d: Any, path: str = "record") -> Any:
    if not isinstance(d, dict):
        raise PocoError(f"{path}: expected an object")
    cls = CLASSES[schema]
    obj = cls()
    spec = SPECS[schema]
    for k, v in d.items():
        if k in spec and not (schema == "poco" and k == "payload"):
            setattr(obj, k, _read(spec[k], v, f"{path}.{k}"))
        elif k not in spec:
            obj.extra[k] = v
    if schema == "poco":
        if obj.schema != SCHEMA:
            raise PocoError(f"{path}.schema: expected {SCHEMA!r}")
        if not obj.id:
            raise PocoError(f"{path}.id: must not be empty")
        payload = d.get("payload", {})
        obj.payload = from_dict(obj.kind, payload, f"{path}.payload") if obj.kind in KINDS else payload
    return obj


def to_dict(obj: Any) -> Dict[str, Any]:
    schema = next(n for n, c in CLASSES.items() if c is type(obj))
    out: Dict[str, Any] = dict(obj.extra)
    for f in dc_fields(obj):
        if f.name == "extra":
            continue
        v = getattr(obj, f.name)
        if schema == "poco" and f.name == "payload":
            out["payload"] = to_dict(v) if not isinstance(v, dict) else v
        else:
            out[f.name] = _write(SPECS[schema][f.name], v)
    return out


def load_record(d: Dict[str, Any]) -> "Record":
    return from_dict("poco", d)
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--schemas", type=Path, default=DEFAULT_SCHEMAS)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = generate(load_schemas(args.schemas))
    if not args.check:
        args.out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.out}")
        return 0
    current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
    if current != text:
        print(f"remaster_poco_python: {args.out} is stale; run Tools/FUSE/Remaster/poco_codegen.py")
        return 1
    # Round-trip a record of every plan kind through the generated module.
    sys.path.insert(0, str(args.out.parent.parent))
    import importlib

    mod = importlib.import_module(args.out.parent.name + "." + args.out.stem)
    sample = {"schema": "fuse.poco/1", "kind": "mesh", "id": "mesh/a", "tags": ["x"], "custom": {"k": 1},
              "provenance": {"origin": "derived", "derived_from": ["oaid:1"], "recipe": None, "ai": None},
              "payload": {"streams": [{"semantic": "Position", "format": "F32x3",
                                       "data": {"sha256": "a" * 64, "size": 12, "media": "fuse/mesh-stream"}}],
                          "bounds": [0, 0, 0, 1, 1, 1], "relight": {"x": 1}}}
    rec = mod.load_record(sample)
    back = mod.to_dict(rec)
    assert back["custom"] == {"k": 1} and back["payload"]["relight"] == {"x": 1}, back
    assert back["payload"]["streams"][0]["data"]["sha256"] == "a" * 64
    assert mod.to_dict(mod.load_record(back)) == back
    for kind in mod.KINDS:
        r = mod.load_record({"schema": "fuse.poco/1", "kind": kind, "id": "k/" + kind, "payload": {}})
        assert mod.to_dict(mod.load_record(mod.to_dict(r))) == mod.to_dict(r)
    for bad in ({"schema": "fuse.poco/2", "kind": "mesh", "id": "x"},
                {"schema": "fuse.poco/1", "kind": "light", "id": "x", "payload": {"type": "Laser"}},
                {"schema": "fuse.poco/1", "kind": "sound", "id": "x", "payload": {"channels": 1.5}}):
        try:
            mod.load_record(bad)
        except mod.PocoError:
            continue
        raise AssertionError(f"accepted {bad}")
    print(f"remaster_poco_python: PASS ({len(mod.CLASSES)} classes, kinds {', '.join(mod.KINDS)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
