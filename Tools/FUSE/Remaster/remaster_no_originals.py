#!/usr/bin/env python3
"""remaster_no_originals: no original game asset is tracked by git (docs/plans/FUSE_REMASTER_PLAN.md W0.6, §0.1.2-4).

Checks, on ``git ls-files --cached`` (committed or staged):

1. **Paths.** Nothing under a per-game cache (``build/remaster-cache/``) or the AI cache (``build/ai-cache/``),
   no Remix-ingested texture (``*.rtex.dds``) and no Remix capture layer (``capture/*.usd[a|c]`` with a
   ``capture`` folder under a ``remaster-cache``-like tree is covered by the first rule).
2. **POCO records** (outside the synthetic ``Tests/**/fixtures/`` trees, §0.1.1). A tracked ``*.poco.json`` must not describe an original (``provenance.origin: original`` or
   ``distribution: never``), and a tracked blob (``.../blobs/sha256/<ab>/<sha256>``) must not be the payload of a
   ``recipe-only`` or ``never`` record (tracked, or in the local caches).
3. **Content hashes (the local original-hash index, when present).** Every ``build/remaster-cache/<game>/``
   may hold ``originals.sha256`` (one lower-case sha256 of an original file's bytes per line, written by the
   importers and capture tools) and a ``store/`` whose ``never`` / ``recipe-only`` records name blobs. A tracked
   file whose sha256 is in that index is an original that slipped into git under another name.
4. **.gitignore** ignores ``build/remaster-cache/<game>/x`` and ``build/ai-cache/x`` (``git check-ignore
   --no-index``).

``--self-test`` first runs the matcher on seeded good and bad paths and on a throw-away git repository with
seeded violations (each must be found, and nothing else). Without git, or outside a work tree, it prints
``REMASTER_NO_ORIGINALS_SKIP`` and exits 77 (ctest SKIP_RETURN_CODE).

    python remaster_no_originals.py --repo <root> [--self-test] [--cache-root <dir>]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Iterable, List, Optional, Set

SKIP = 77
BAD_PATH_RES = [
    re.compile(r"(^|/)build/remaster-cache/"),
    re.compile(r"(^|/)build/ai-cache/"),
    re.compile(r"(^|/)remaster-cache/"),
    re.compile(r"\.rtex\.dds$"),
]
# Synthetic test fixtures (plan §0.1.1: generated by FUSE's own writers, e.g. the Relight importer's expected
# stores for a made-up "fixture_game") may hold records marked original; only the record check skips them.
SYNTHETIC_FIXTURES = re.compile(r"^tests/(.+/)?fixtures/")
BLOB_RE = re.compile(r"(^|/)blobs/sha256/([0-9a-f]{2})/([0-9a-f]{64})$")
MUST_IGNORE = ["build/remaster-cache/game/capture/stage.usda", "build/remaster-cache/game/originals.sha256",
               "build/ai-cache/ab/entry.json"]


def path_violation(path: str) -> Optional[str]:
    p = path.replace("\\", "/").lower()
    for rx in BAD_PATH_RES:
        if rx.search(p):
            return f"{path}: tracked file in a cache of originals / Remix ingest output ({rx.pattern})"
    return None


def git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=check)


def git_available(repo: Path) -> bool:
    if shutil.which("git") is None:
        return False
    try:
        r = git(repo, "rev-parse", "--is-inside-work-tree", check=False)
    except OSError:
        return False
    return r.returncode == 0 and r.stdout.strip() == "true"


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def blob_refs(node) -> Iterable[str]:
    """Every BlobRef sha256 inside a POCO payload."""
    stack = [node]
    while stack:
        v = stack.pop()
        if isinstance(v, dict):
            if isinstance(v.get("sha256"), str) and "media" in v:
                yield v["sha256"]
            stack.extend(v.values())
        elif isinstance(v, list):
            stack.extend(v)


def record_is_original(rec: dict) -> bool:
    prov = rec.get("provenance") or {}
    return prov.get("origin") == "original" or rec.get("distribution") == "never"


def record_not_shippable(rec: dict) -> bool:
    return record_is_original(rec) or rec.get("distribution") == "recipe-only"


def load_record(p: Path) -> Optional[dict]:
    try:
        rec = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeDecodeError):
        return None
    return rec if isinstance(rec, dict) and rec.get("schema") == "fuse.poco/1" else None


def local_index(cache_root: Path) -> tuple[Set[str], Set[str]]:
    """(original file hashes, blob hashes of non-shippable records) from the per-game caches."""
    originals: Set[str] = set()
    restricted_blobs: Set[str] = set()
    if not cache_root.is_dir():
        return originals, restricted_blobs
    for game in sorted(cache_root.iterdir()):
        if not game.is_dir():
            continue
        idx = game / "originals.sha256"
        if idx.is_file():
            for line in idx.read_text(encoding="utf-8", errors="replace").splitlines():
                tok = line.strip().split()[0] if line.strip() else ""
                if re.fullmatch(r"[0-9a-f]{64}", tok):
                    originals.add(tok)
        for rec_path in sorted(game.rglob("*.poco.json")):
            rec = load_record(rec_path)
            if rec and record_not_shippable(rec):
                restricted_blobs.update(blob_refs(rec.get("payload")))
    return originals, restricted_blobs


def scan(repo: Path, cache_root: Path) -> tuple[List[str], int]:
    out = git(repo, "-c", "core.quotepath=off", "ls-files", "--cached", "-z").stdout
    files = [f for f in out.split("\0") if f]
    violations: List[str] = []
    originals, restricted = local_index(cache_root)
    tracked_records: List[str] = [f for f in files if f.endswith(".poco.json")]
    for f in tracked_records:
        if SYNTHETIC_FIXTURES.search(f.lower()):
            continue  # §0.1.1: repository test fixtures are synthetic (FUSE-written); path and hash checks still apply
        rec = load_record(repo / f)
        if rec is None:
            continue
        if record_is_original(rec):
            violations.append(f"{f}: POCO record of an original asset (origin original / distribution never) is tracked")
        if record_not_shippable(rec):
            restricted.update(blob_refs(rec.get("payload")))
    for f in files:
        v = path_violation(f)
        if v:
            violations.append(v)
        m = BLOB_RE.search(f.lower())
        if m and m.group(3) in restricted:
            violations.append(f"{f}: blob of a recipe-only / never record is tracked")
    if originals:
        for f in files:
            p = repo / f
            try:
                if p.is_file() and sha256_file(p) in originals:
                    violations.append(f"{f}: content matches an original in the local original-hash index")
            except OSError:
                pass
    for name in MUST_IGNORE:
        r = git(repo, "check-ignore", "-q", "--no-index", name, check=False)
        if r.returncode != 0:
            violations.append(f".gitignore does not ignore {name}")
    return sorted(set(violations)), len(files)


def self_test() -> int:
    errors = 0
    bad = ["build/remaster-cache/tge/capture/stage.usda", "Build/AI-Cache/ab/x.json", "x/remaster-cache/g/a.png",
           "Content/remaster/g/textures/wall.a.rtex.dds"]
    good = ["Content/remaster/g/recipes/tex-upscale.json", "docs/plans/FUSE_REMASTER_PLAN.md", "build.gradle",
            "Tools/FUSE/Remaster/remaster_no_originals.py", "textures/wall.dds"]
    for p in bad:
        if not path_violation(p):
            print(f"self-test: seeded bad path not flagged: {p}")
            errors += 1
    for p in good:
        if path_violation(p):
            print(f"self-test: allowed path flagged: {p}")
            errors += 1
    if shutil.which("git") is None:
        print("self-test: git not found, repository part skipped")
        return errors
    with tempfile.TemporaryDirectory(prefix="remaster_no_originals_") as tmp:
        repo = Path(tmp) / "repo"
        repo.mkdir()
        git(repo, "init", "-q")
        (repo / ".gitignore").write_text("build\n", encoding="utf-8")

        def write(rel: str, data: bytes) -> None:
            p = repo / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)

        original_png = b"\x89PNG original pixels of the game"
        derived_png = b"upscaled derivative"
        library_png = b"our own CC0 texture"
        sha = lambda b: hashlib.sha256(b).hexdigest()  # noqa: E731

        def rec(kind: str, rid: str, origin: str, dist: str, blob: bytes) -> bytes:
            return json.dumps({"schema": "fuse.poco/1", "kind": kind, "id": rid, "provenance": {"origin": origin},
                               "distribution": dist,
                               "payload": {"albedo": {"sha256": sha(blob), "size": len(blob), "media": "image/png"}}}).encode()

        # Good: a library record + its blob, a recipe.
        write("Content/store/poco/texture_set/lib/a.poco.json", rec("texture_set", "lib/a", "library", "ship", library_png))
        write(f"Content/store/blobs/sha256/{sha(library_png)[:2]}/{sha(library_png)}", library_png)
        write("Content/remaster/g/recipes/r.json", b"{}")
        write("Tests/relight/fixtures/x/expected/poco/mesh/cap.poco.json", rec("mesh", "cap", "original", "never", b"synthetic"))
        # Bad: an original's record, a derived (recipe-only) record's blob, an original renamed, a .rtex.dds.
        write("Content/store/poco/texture_set/cap/o.poco.json", rec("texture_set", "cap/o", "original", "never", original_png))
        write("Content/store/poco/texture_set/up/d.poco.json", rec("texture_set", "up/d", "derived", "recipe-only", derived_png))
        write(f"Content/store/blobs/sha256/{sha(derived_png)[:2]}/{sha(derived_png)}", derived_png)
        write("Content/art/innocent_name.png", original_png)
        write("Content/mods/x/wall.a.rtex.dds", b"dds")
        # The local cache (ignored) with the original-hash index.
        write("build/remaster-cache/g/originals.sha256", (sha(original_png) + "  textures/wall.png\n").encode())
        git(repo, "add", "-A")
        # A file forced past .gitignore into the cache path.
        write("build/remaster-cache/g/capture/stage.usda", b"#usda 1.0")
        git(repo, "add", "-f", "build/remaster-cache/g/capture/stage.usda")
        found, n = scan(repo, repo / "build" / "remaster-cache")
        expect = [
            "Content/store/poco/texture_set/cap/o.poco.json: POCO record",
            f"Content/store/blobs/sha256/{sha(derived_png)[:2]}/{sha(derived_png)}: blob of a recipe-only",
            "Content/art/innocent_name.png: content matches an original",
            "Content/mods/x/wall.a.rtex.dds: tracked file",
            "build/remaster-cache/g/capture/stage.usda: tracked file",
        ]
        for e in expect:
            if not any(v.startswith(e) for v in found):
                print(f"self-test: seeded violation not found: {e}")
                errors += 1
        if len(found) != len(expect):
            print(f"self-test: expected {len(expect)} violations in the seeded repo, found {len(found)}:")
            for v in found:
                print(f"  {v}")
            errors += 1
        # Without the cache index the renamed original is invisible (the gate degrades, it does not fail).
        found2, _ = scan(repo, repo / "missing-cache")
        if any("content matches" in v for v in found2):
            print("self-test: content check ran without an index")
            errors += 1
        print(f"self-test: {len(bad)} bad / {len(good)} good paths, seeded repo with {n} files: "
              f"{len(found)} violations found as expected" if errors == 0 else "self-test: FAILED")
    return errors


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", required=True, type=Path)
    ap.add_argument("--cache-root", type=Path, help="default: <repo>/build/remaster-cache")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args(argv)
    repo = args.repo.resolve()
    if args.self_test and self_test() != 0:
        print("remaster_no_originals: FAILED (self-test)")
        return 1
    if not git_available(repo):
        print(f"REMASTER_NO_ORIGINALS_SKIP: git not found or {repo} is not a git work tree")
        return SKIP
    violations, n = scan(repo, args.cache_root or repo / "build" / "remaster-cache")
    for v in violations:
        print(f"violation: {v}")
    if violations:
        print(f"remaster_no_originals: FAILED ({len(violations)} violations in {n} tracked files)")
        return 1
    print(f"remaster_no_originals: PASS ({n} tracked files, no originals; caches ignored)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
