const char* cooked_mesh_path_name(CookedMeshPath path) { return path == CookedMeshPath::Adopted ? "adopted" : "built"; }

bool cooked_mesh_to_meshlets(const asset::CookedMesh& mesh, CookedMeshletResult& out, std::string* error,
                             kernel::Backend backend) {
    out = CookedMeshletResult{};
    const u32 n = mesh.vertex_count();
    if (n == 0u || mesh.positions.size() != static_cast<usize>(n) * 3u || mesh.indices.empty() ||
        mesh.indices.size() % 3u != 0u) {
        return fail(error, "no triangles");
    }
    sourceBounds(mesh, out.boundsMin, out.boundsMax);
    const std::string blocker = adoptBlocker(mesh);
    if (blocker.empty()) {
        std::string why;
        if (adopt(mesh, out, backend, &why)) {
            return true;
        }
        // An inconsistent section is not fatal: the streams are enough to build meshlets.
        out.note = why;
    } else {
        out.note = blocker;
    }
    const std::string note = out.note;
    f32 lo[3];
    f32 hi[3];
    std::memcpy(lo, out.boundsMin, sizeof(lo));
    std::memcpy(hi, out.boundsMax, sizeof(hi));
    if (!build(mesh, out, backend, error)) {
        return false;
    }
    out.note = note;
    std::memcpy(out.boundsMin, lo, sizeof(lo));
    std::memcpy(out.boundsMax, hi, sizeof(hi));
    return true;
}

