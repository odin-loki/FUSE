#!/usr/bin/env python3
"""Generates Source/FUSE/UI/Text/src/unicode_tables.inc (UAX #29 grapheme tables) from the Unicode Character Database.

Usage: python gen_unicode_tables.py <ucd dir> [out file]
<ucd dir> holds GraphemeBreakProperty.txt, emoji-data.txt and DerivedCoreProperties.txt of one Unicode version
(https://www.unicode.org/Public/<version>/ucd/, auxiliary/ and emoji/). Hangul LV / LVT syllables are computed in code,
so they are left out of the table.
"""
import os
import re
import sys

GCB = {"CR": "CR", "LF": "LF", "Control": "Control", "Extend": "Extend", "ZWJ": "ZWJ",
       "Regional_Indicator": "RegionalIndicator", "Prepend": "Prepend", "SpacingMark": "SpacingMark",
       "L": "L", "V": "V", "T": "T"}


def ranges(path, want):
    """Yields (lo, hi, value) for lines whose second field passes want(fields)."""
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        v = want(f)
        if v is None:
            continue
        a, _, b = f[0].partition("..")
        yield int(a, 16), int(b or a, 16), v


def merge(items):
    items = sorted(items)
    out = []
    for lo, hi, v in items:
        if out and out[-1][2] == v and out[-1][1] + 1 == lo:
            out[-1] = (out[-1][0], hi, v)
        else:
            out.append((lo, hi, v))
    return out


def main():
    ucd = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "src", "unicode_tables.inc")
    gbp = os.path.join(ucd, "GraphemeBreakProperty.txt")
    version = re.search(r"GraphemeBreakProperty-([\d.]+)\.txt", open(gbp, encoding="utf-8").readline()).group(1)
    gcb = list(ranges(gbp, lambda f: GCB.get(f[1])))
    pict = list(ranges(os.path.join(ucd, "emoji-data.txt"),
                       lambda f: "ExtPict" if f[1] == "Extended_Pictographic" else None))
    # Extended_Pictographic code points are all Grapheme_Cluster_Break=Other: one table carries both.
    taken = set()
    for lo, hi, _ in gcb:
        taken.update(range(lo, hi + 1))
    for lo, hi, _ in pict:
        assert not any(c in taken for c in range(lo, hi + 1)), hex(lo)
    gb = merge(gcb + pict)
    incb = merge(ranges(os.path.join(ucd, "DerivedCoreProperties.txt"),
                        lambda f: f[2] if len(f) > 2 and f[1] == "InCB" else None))

    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write(f"// Generated by Text/tools/gen_unicode_tables.py from the Unicode {version} UCD. Do not edit.\n")
        o.write("// Grapheme_Cluster_Break (Hangul LV / LVT computed in code) merged with Extended_Pictographic.\n")
        o.write(f"inline constexpr char kUnicodeVersion[] = \"{version}\";\n")
        o.write("inline constexpr GbRange kGraphemeBreak[] = {\n")
        for i in range(0, len(gb), 3):
            o.write("    " + " ".join(f"{{0x{lo:04X}, 0x{hi:04X}, GB::{v}}}," for lo, hi, v in gb[i:i + 3]) + "\n")
        o.write("};\n")
        o.write("// Indic_Conjunct_Break (DerivedCoreProperties): Linker, Consonant, Extend.\n")
        o.write("inline constexpr IncbRange kIncb[] = {\n")
        for i in range(0, len(incb), 3):
            o.write("    " + " ".join(f"{{0x{lo:04X}, 0x{hi:04X}, Incb::{v}}}," for lo, hi, v in incb[i:i + 3]) + "\n")
        o.write("};\n")
    print(f"{out}: Unicode {version}, {len(gb)} grapheme ranges, {len(incb)} InCB ranges")


if __name__ == "__main__":
    main()
