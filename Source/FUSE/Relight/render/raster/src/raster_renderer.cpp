    bool ensureShadowMap(std::uint32_t size, std::uint64_t serial);
    VkShaderModule module(const std::uint32_t* words, std::size_t bytes);
    VkPipeline createPipeline(VkShaderModule vs, VkShaderModule fs, const VkFormat* colors, std::uint32_t colorCount,
                              VkFormat depth, const VkPipelineColorBlendAttachmentState* blend);
    bool ensurePipelines(VkFormat output);
    VkPipeline forwardPipeline(const scene::BlendMode& b);
    bool ensureBuffer(rr::Buffer& b, std::size_t bytes, const char* name, std::uint64_t serial);
    std::uint32_t samplerHandle(const tap::CaptureDrawRecord::SamplerFacts& s);
    void setDrawState(VkCommandBuffer cmd, const RasterDraw& d) const;
    void beginPass(VkCommandBuffer cmd, VkPipeline pipeline) const;

    RasterConfig m_config;
    rf::RendererContext* m_context = nullptr;
    tap::IFrameHost* m_host = nullptr;
    rf::BindlessImageRegistry* m_registry = nullptr;
    VkDevice m_device = VK_NULL_HANDLE;
    std::string m_error;
    TierPlan m_plan;
    std::uint32_t m_available = implementedFeatures();

