VkShaderModule RasterRenderer::module(const std::uint32_t* words, std::size_t bytes) {
    VkShaderModuleCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
    ci.codeSize = bytes;
    ci.pCode = words;
    VkShaderModule m = VK_NULL_HANDLE;
    return vkCreateShaderModule(m_device, &ci, nullptr, &m) == VK_SUCCESS ? m : VK_NULL_HANDLE;
}

VkPipeline RasterRenderer::createPipeline(VkShaderModule vs, VkShaderModule fs, const VkFormat* colors,
                                          std::uint32_t colorCount, VkFormat depth,
                                          const VkPipelineColorBlendAttachmentState* blend) {
    VkPipelineShaderStageCreateInfo stages[2]{};
    stages[0].sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stages[0].stage = VK_SHADER_STAGE_VERTEX_BIT;
    stages[0].module = vs;
    stages[0].pName = "main";
    stages[1] = stages[0];
    stages[1].stage = VK_SHADER_STAGE_FRAGMENT_BIT;
    stages[1].module = fs;
    VkPipelineVertexInputStateCreateInfo vertexInput{};
    vertexInput.sType = VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO;
    VkPipelineInputAssemblyStateCreateInfo assembly{};
    assembly.sType = VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO;
    assembly.topology = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;
    VkPipelineViewportStateCreateInfo viewport{};
    viewport.sType = VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO;
    viewport.viewportCount = 1;
    viewport.scissorCount = 1;
    VkPipelineRasterizationStateCreateInfo raster{};
    raster.sType = VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO;
    raster.polygonMode = VK_POLYGON_MODE_FILL;
    raster.lineWidth = 1.f;
    VkPipelineMultisampleStateCreateInfo multisample{};
    multisample.sType = VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO;
    multisample.rasterizationSamples = VK_SAMPLE_COUNT_1_BIT;
    VkPipelineDepthStencilStateCreateInfo ds{};
    ds.sType = VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO;
    ds.depthCompareOp = VK_COMPARE_OP_LESS_OR_EQUAL;
    VkPipelineColorBlendStateCreateInfo cb{};
    cb.sType = VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO;
    VkPipelineColorBlendAttachmentState opaque[kGBufferTargets]{};
    for (VkPipelineColorBlendAttachmentState& a : opaque) {
        a.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT | VK_COLOR_COMPONENT_B_BIT |
                           VK_COLOR_COMPONENT_A_BIT;
    }
    cb.attachmentCount = colorCount;
    cb.pAttachments = blend ? blend : opaque;
    const VkDynamicState dynamic[] = {VK_DYNAMIC_STATE_VIEWPORT,          VK_DYNAMIC_STATE_SCISSOR,
                                      VK_DYNAMIC_STATE_CULL_MODE,         VK_DYNAMIC_STATE_FRONT_FACE,
                                      VK_DYNAMIC_STATE_DEPTH_TEST_ENABLE, VK_DYNAMIC_STATE_DEPTH_WRITE_ENABLE,
                                      VK_DYNAMIC_STATE_DEPTH_COMPARE_OP,  VK_DYNAMIC_STATE_BLEND_CONSTANTS};
    VkPipelineDynamicStateCreateInfo dyn{};
    dyn.sType = VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO;
    dyn.dynamicStateCount = static_cast<std::uint32_t>(std::size(dynamic));
    dyn.pDynamicStates = dynamic;
    VkPipelineRenderingCreateInfo rendering{};
    rendering.sType = VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO;
    rendering.colorAttachmentCount = colorCount;
    rendering.pColorAttachmentFormats = colors;
    rendering.depthAttachmentFormat = depth;
    VkGraphicsPipelineCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO;
    ci.pNext = &rendering;
    ci.flags = m_context->bindless().pipelineCreateFlags();
    ci.stageCount = fs != VK_NULL_HANDLE ? 2u : 1u;
    ci.pStages = stages;
    ci.pVertexInputState = &vertexInput;
    ci.pInputAssemblyState = &assembly;
    ci.pViewportState = &viewport;
    ci.pRasterizationState = &raster;
    ci.pMultisampleState = &multisample;
    ci.pDepthStencilState = &ds;
    ci.pColorBlendState = &cb;
    ci.pDynamicState = &dyn;
    ci.layout = m_layout;
    VkPipeline p = VK_NULL_HANDLE;
    return vkCreateGraphicsPipelines(m_device, VK_NULL_HANDLE, 1, &ci, nullptr, &p) == VK_SUCCESS ? p : VK_NULL_HANDLE;
}

bool RasterRenderer::ensurePipelines(VkFormat output) {
    if (!m_gbuffer) {
        const VkFormat colors[kGBufferTargets] = {kAlbedoFormat, kNormalFormat, kEmissiveFormat, kPositionFormat};
        m_gbuffer = createPipeline(m_surfaceVs, m_gbufferFs, colors, kGBufferTargets, kDepthFormat, nullptr);
        if (!m_gbuffer) {
            m_error = "G-buffer pipeline creation failed";
            return false;
        }
    }
    if (!m_decal && (m_available & kFeatureDecals)) {
        VkPipelineColorBlendAttachmentState b{};
        b.blendEnable = VK_TRUE;
        b.srcColorBlendFactor = VK_BLEND_FACTOR_SRC_ALPHA;
        b.dstColorBlendFactor = VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
        b.colorBlendOp = VK_BLEND_OP_ADD;
        b.srcAlphaBlendFactor = VK_BLEND_FACTOR_ZERO;
        b.dstAlphaBlendFactor = VK_BLEND_FACTOR_ONE;
        b.alphaBlendOp = VK_BLEND_OP_ADD;
        b.colorWriteMask = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT | VK_COLOR_COMPONENT_B_BIT;
        const VkFormat albedo = kAlbedoFormat;
        m_decal = createPipeline(m_surfaceVs, m_decalFs, &albedo, 1, kDepthFormat, &b);
        if (!m_decal) {
            m_available &= ~static_cast<std::uint32_t>(kFeatureDecals); // degrade: decals drawn as opaque
        }
    }
    if (!m_shadowPipe && (m_available & kFeatureShadows)) {
        m_shadowPipe = createPipeline(m_surfaceVs, m_shadowFs, nullptr, 0, kDepthFormat, nullptr);
        if (!m_shadowPipe) {
            m_available &= ~static_cast<std::uint32_t>(kFeatureShadows);
        }
    }
    if (m_outputFormat != output) {
        if (m_light) {
            m_oldPipelines.push_back(m_light);
            m_light = VK_NULL_HANDLE;
        }
        for (auto& [key, p] : m_forward) {
            m_oldPipelines.push_back(p);
        }
        m_forward.clear();
        m_outputFormat = output;
    }
    if (!m_light) {
        m_light = createPipeline(m_lightVs, m_lightFs, &output, 1, VK_FORMAT_UNDEFINED, nullptr);
        if (!m_light) {
            m_error = "lighting pipeline creation failed";
            return false;
        }
    }
    return true;
}

VkPipeline RasterRenderer::forwardPipeline(const scene::BlendMode& b) {
    const BlendKey key{b.enableBlending, b.colorSrcFactor, b.colorDstFactor, b.colorBlendOp, b.alphaSrcFactor,
                       b.alphaDstFactor, b.alphaBlendOp, b.writeMask, static_cast<std::uint32_t>(m_outputFormat)};
    auto it = m_forward.find(key);
    if (it != m_forward.end()) {
        return it->second;
    }
    VkPipelineColorBlendAttachmentState a{};
    a.blendEnable = b.enableBlending ? VK_TRUE : VK_FALSE;
    a.srcColorBlendFactor = static_cast<VkBlendFactor>(b.colorSrcFactor);
    a.dstColorBlendFactor = static_cast<VkBlendFactor>(b.colorDstFactor);
    a.colorBlendOp = static_cast<VkBlendOp>(b.colorBlendOp);
    a.srcAlphaBlendFactor = static_cast<VkBlendFactor>(b.alphaSrcFactor);
    a.dstAlphaBlendFactor = static_cast<VkBlendFactor>(b.alphaDstFactor);
    a.alphaBlendOp = static_cast<VkBlendOp>(b.alphaBlendOp);
    a.colorWriteMask = b.writeMask & 0xfu;
    const VkFormat output = m_outputFormat;
    const VkPipeline p = createPipeline(m_surfaceVs, m_forwardFs, &output, 1, kDepthFormat, &a);
    m_forward.emplace(key, p);
    return p;
}

