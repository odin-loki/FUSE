std::uint32_t memoryTypeFor(VkPhysicalDevice pd, std::uint32_t bits, VkMemoryPropertyFlags flags) {
    VkPhysicalDeviceMemoryProperties p{};
    vkGetPhysicalDeviceMemoryProperties(pd, &p);
    for (std::uint32_t i = 0; i < p.memoryTypeCount; ++i) {
        if ((bits & (1u << i)) && (p.memoryTypes[i].propertyFlags & flags) == flags) {
            return i;
        }
    }
    return UINT32_MAX;
}

bool RasterRenderer::createTarget(Target& t, VkFormat format, std::uint32_t w, std::uint32_t h,
                                  VkImageUsageFlags usage, VkImageAspectFlags aspect) {
    t = Target{};
    VkImageCreateInfo ci{};
    ci.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
    ci.imageType = VK_IMAGE_TYPE_2D;
    ci.format = format;
    ci.extent = {w, h, 1};
    ci.mipLevels = 1;
    ci.arrayLayers = 1;
    ci.samples = VK_SAMPLE_COUNT_1_BIT;
    ci.tiling = VK_IMAGE_TILING_OPTIMAL;
    ci.usage = usage | VK_IMAGE_USAGE_SAMPLED_BIT;
    ci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    ci.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    if (vkCreateImage(m_device, &ci, nullptr, &t.image) != VK_SUCCESS) {
        t.image = VK_NULL_HANDLE;
        return false;
    }
    VkMemoryRequirements req{};
    vkGetImageMemoryRequirements(m_device, t.image, &req);
    VkMemoryAllocateInfo mi{};
    mi.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    mi.allocationSize = req.size;
    const VkPhysicalDevice pd = static_cast<VkPhysicalDevice>(m_context->device().nativePhysicalDevice());
    mi.memoryTypeIndex = memoryTypeFor(pd, req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    if (mi.memoryTypeIndex == UINT32_MAX) {
        mi.memoryTypeIndex = memoryTypeFor(pd, req.memoryTypeBits, 0);
    }
    if (mi.memoryTypeIndex == UINT32_MAX || vkAllocateMemory(m_device, &mi, nullptr, &t.memory) != VK_SUCCESS ||
        vkBindImageMemory(m_device, t.image, t.memory, 0) != VK_SUCCESS) {
        destroyTarget(t);
        return false;
    }
    VkImageViewCreateInfo vi{};
    vi.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
    vi.image = t.image;
    vi.viewType = VK_IMAGE_VIEW_TYPE_2D;
    vi.format = format;
    vi.subresourceRange = {aspect, 0, 1, 0, 1};
    if (vkCreateImageView(m_device, &vi, nullptr, &t.view) != VK_SUCCESS) {
        t.view = VK_NULL_HANDLE;
        destroyTarget(t);
        return false;
    }
    t.format = format;
    t.width = w;
    t.height = h;
    rr::Texture tex;
    tex.image = t.image;
    tex.view = t.view;
    tex.desc.width = w;
    tex.desc.height = h;
    tex.desc.format = static_cast<rr::GpuFormat>(format);
    tex.desc.usage = rr::ImageUsage::Sampled;
    t.slot = m_context->bindless().registerTextureSlot(tex, false);
    t.handle = m_context->bindless().shaderHandle(t.slot);
    if (!t.handle) {
        destroyTarget(t);
        return false;
    }
    return true;
}

void RasterRenderer::destroyTarget(Target& t) {
    if (t.view != VK_NULL_HANDLE) {
        vkDestroyImageView(m_device, t.view, nullptr);
    }
    if (t.image != VK_NULL_HANDLE) {
        vkDestroyImage(m_device, t.image, nullptr);
    }
    if (t.memory != VK_NULL_HANDLE) {
        vkFreeMemory(m_device, t.memory, nullptr);
    }
    t = Target{};
}

void RasterRenderer::retireTarget(Target& t, std::uint64_t serial) {
    if (!t.valid()) {
        return;
    }
    if (t.slot.isValid()) {
        m_context->bindless().retireSlot(t.slot, serial);
    }
    m_retiredTargets.emplace_back(t, serial);
    t = Target{};
}

bool RasterRenderer::ensureTargets(std::uint32_t w, std::uint32_t h, std::uint64_t serial) {
    if (m_depth.valid() && m_depth.width == w && m_depth.height == h) {
        return true;
    }
    for (Target& t : m_targets) {
        retireTarget(t, serial);
    }
    retireTarget(m_depth, serial);
    const VkFormat formats[kGBufferTargets] = {kAlbedoFormat, kNormalFormat, kEmissiveFormat, kPositionFormat};
    for (std::uint32_t i = 0; i < kGBufferTargets; ++i) {
        if (!createTarget(m_targets[i], formats[i], w, h, VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT, VK_IMAGE_ASPECT_COLOR_BIT)) {
            m_error = "G-buffer target creation failed";
            return false;
        }
    }
    if (!createTarget(m_depth, kDepthFormat, w, h, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT, VK_IMAGE_ASPECT_DEPTH_BIT)) {
        m_error = "depth target creation failed";
        return false;
    }
    return true;
}

bool RasterRenderer::ensureShadowMap(std::uint32_t size, std::uint64_t serial) {
    if (m_shadow.valid() && m_shadow.width == size) {
        return true;
    }
    retireTarget(m_shadow, serial);
    return createTarget(m_shadow, kDepthFormat, size, size, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT,
                        VK_IMAGE_ASPECT_DEPTH_BIT);
}

bool RasterRenderer::ensureBuffer(rr::Buffer& b, std::size_t bytes, const char* name, std::uint64_t serial) {
    if (b.handle && b.desc.size >= bytes) {
        return true;
    }
    if (b.handle) {
        m_retiredBuffers.emplace_back(b, serial);
        b = rr::Buffer{};
    }
    rr::BufferDesc d;
    d.size = std::max<std::size_t>(bytes + bytes / 2, 4096);
    d.usage = static_cast<rr::BufferUsage>(static_cast<std::uint32_t>(rr::BufferUsage::Storage) |
                                          static_cast<std::uint32_t>(rr::BufferUsage::ShaderDeviceAddress));
    d.memoryUsage = rr::MemoryUsage::CpuToGpu;
    d.name = name;
    return m_context->allocator().createBuffer(d, b) && b.mapped != nullptr && b.deviceAddress != 0;
}

std::uint32_t RasterRenderer::samplerHandle(const tap::CaptureDrawRecord::SamplerFacts& s) {
    // D3DTADDRESS: 1 wrap, 2 mirror, 3 clamp, 4 border, 5 mirror once; D3DTEXF: <= 1 nearest.
    const std::uint32_t address = s.addressU == 2 ? VK_SAMPLER_ADDRESS_MODE_MIRRORED_REPEAT
                                  : s.addressU == 3 ? VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE
                                  : s.addressU == 4 ? VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_BORDER
                                  : s.addressU == 5 ? VK_SAMPLER_ADDRESS_MODE_MIRROR_CLAMP_TO_EDGE
                                                    : VK_SAMPLER_ADDRESS_MODE_REPEAT;
    const std::uint32_t filter = s.magFilter <= 1 ? VK_FILTER_NEAREST : VK_FILTER_LINEAR;
    const std::uint32_t key = address | filter << 8;
    auto it = m_samplers.find(key);
    if (it != m_samplers.end()) {
        return it->second.second;
    }
    rr::SamplerDesc d;
    d.minFilter = filter;
    d.magFilter = filter;
    d.addressMode = address;
    d.maxLod = 0.f; // mip 0: the capture samples the base level of legacy textures
    d.name = "relight.raster.sampler";
    const rr::BindlessSlotHandle slot = m_context->bindless().acquireSampler(d);
    const std::uint32_t handle = m_context->bindless().shaderHandle(slot);
    m_samplers.emplace(key, std::make_pair(slot, handle));
    return handle;
}

