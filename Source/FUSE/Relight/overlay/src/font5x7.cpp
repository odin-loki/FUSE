const std::uint8_t* glyph5x7(char c) {
    const int code = static_cast<unsigned char>(c);
    const int index = (code >= 32 && code <= 126) ? code - 32 : ('?' - 32);
    return kTable[static_cast<std::size_t>(index)].data();
}

