constexpr std::uint8_t rowBits(const char* row) {
    std::uint8_t bits = 0;
    for (int i = 0; i < kGlyphWidth; ++i) {
        bits = static_cast<std::uint8_t>((bits << 1) | (row[i] == '#' ? 1 : 0));
    }
    return bits;
}

constexpr std::array<std::array<std::uint8_t, kGlyphHeight>, 95> buildTable() {
    std::array<std::array<std::uint8_t, kGlyphHeight>, 95> t{};
    for (int g = 0; g < 95; ++g) {
        for (int r = 0; r < kGlyphHeight; ++r) {
            t[static_cast<std::size_t>(g)][static_cast<std::size_t>(r)] = rowBits(kGlyphs[g].rows[r]);
        }
    }
    return t;
}

constexpr auto kTable = buildTable();
static_assert(kTable[33][0] == 0x0E && kTable[33][3] == 0x1F, "glyph 'A' encodes as expected");

